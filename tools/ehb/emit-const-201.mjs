#!/usr/bin/env node
// Genera `out/ehb/const_game_201.h` (assetes estáticos de la demo 201) a partir
// del `.h` que emite slice-tiles (tilebank_indexed.h) y de tiles.json. Así el
// ensamblado manual deja de existir: es un renombrado determinista de una sola
// fuente (pipeline canónico, regla 7).
//
// Uso: node tools/ehb/emit-const-201.mjs [--in out/ehb/tilebank_indexed.h] [--out out/ehb/const_game_201.h]
import fs from 'node:fs';
import path from 'node:path';

const argV = (n, d) => { const i = process.argv.indexOf(n); return i >= 0 ? process.argv[i + 1] : d; };
const inH = path.resolve(argV('--in', 'out/ehb/tilebank_indexed.h'));
const outH = path.resolve(argV('--out', 'out/ehb/const_game_201.h'));
const json = JSON.parse(fs.readFileSync(path.resolve(argV('--json', 'out/ehb/tiles.json')), 'utf8'));

const hdr = fs.readFileSync(inH, 'utf8');
const body = (id) => { const m = hdr.match(new RegExp(id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?:\\[\\d+\\])+\\s*=\\s*\\{([\\s\\S]*?)\\};')); return m ? m[1] : null; };
const num = (id) => { const b = body(id); return b ? b.match(/\d+/g).map(Number) : null; };

const palNum = num('kTileIndexedPalette');
const mapNum = num('kTileIndexedMap');
if (!palNum || !mapNum) { console.error(`[emit] no encontré kTileIndexedPalette/kTileIndexedMap en ${inH}`); process.exit(1); }
const stride = /kTileBankStride = (\d+);/.exec(hdr)?.[1];
const bytes = /kTileBankBytes = (\d+);/.exec(hdr)?.[1];

const cols = json.cols, rows = json.rows, tile = json.tile;
const paletteLines = [];
for (let r = 0; r < palNum.length; r += 36) paletteLines.push('  ' + palNum.slice(r, r + 36).join(',') + ',');
const randLines = [];
for (let y = 0; y < rows; y++) randLines.push('  { ' + mapNum.slice(y * cols, (y + 1) * cols).join(',') + ' },');

const out = [
  '// Static EHB assets (generated by tools/ehb/emit-const-201.mjs). Paleta 64 (base+half).',
  `// CONVENCION BASES-PRIMERO: indices 0..31 = base, 32..63 = half. Listo para el`,
  `// chipset EHB sin transformacion CPU en el Amiga (regla 7; slice-tiles lo exporta asi).`,
  `// ${tile}x${tile} tiles, mapa ${cols}x${rows}; banco raw incbin (stride ${stride}, ${bytes} B).`,
  `extern "C" const unsigned char g_tilebank_raw[];`,
  `extern "C" const unsigned int g_tilebank_raw_size;`,
  `static const unsigned char kEhbPalette[${palNum.length}] = {`,
  ...paletteLines,
  '};',
  `static const unsigned short kRenderMap[${rows}][${cols}] = {`,
  ...randLines,
  '};',
  '',
].join('\n');

fs.writeFileSync(outH, out, 'utf8');
console.log(`[emit] ${outH} (${palNum.length} colores, ${mapNum.length} tiles en mapa, stride ${stride}, ${bytes} B)`);
